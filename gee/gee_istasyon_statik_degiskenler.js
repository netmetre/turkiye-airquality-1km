function tamponla(m) {
  return istasyonlar.map(function(f) { return f.buffer(m).set('tampon_m', m); });
}

// ---- 1) Topografya: SRTM 30 m ----
var dem = ee.Image('USGS/SRTMGL1_003').select('elevation');
var egim = ee.Terrain.slope(dem).rename('egim_derece');
var topo = istasyonlar.map(function(f) {
  var nokta = dem.addBands(egim).reduceRegion({
    reducer: ee.Reducer.first(), geometry: f.geometry(), scale: 30});
  var cevre5 = dem.reduceRegion({
    reducer: ee.Reducer.mean().combine(ee.Reducer.stdDev(), '', true),
    geometry: f.geometry().buffer(5000), scale: 90});
  var cevre1 = dem.reduceRegion({
    reducer: ee.Reducer.mean(), geometry: f.geometry().buffer(1000), scale: 30});
  var yuk = ee.Number(nokta.get('elevation'));
  return f.set({
    yukseklik_m: yuk,
    egim_derece: nokta.get('egim_derece'),
    yukseklik_ort_1km: cevre1.get('elevation'),
    yukseklik_ort_5km: cevre5.get('elevation_mean'),
    yukseklik_std_5km: cevre5.get('elevation_stdDev'),
    goreli_yukseklik_5km: yuk.subtract(ee.Number(cevre5.get('elevation_mean')))
  }).setGeometry(null);
});
